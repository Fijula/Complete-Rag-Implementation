#Step2 : Split knowledge base into chunks
def chunk_text(text,chunk_size=20):
  words= text.split()
  chunks=[]
  for i in range(0,len(words),chunk_size): #chunk_size is step
    chunk= " ".join(words[i:i+chunk_size])
    chunks.append(chunk)
  return chunks

knwoledge_chunks= chunk_text(knowlwdge_base,10)
print(knwoledge_chunks)

import openai
from openai import OpenAI
from google.colab import userdata

openai_key = userdata.get('OpenAI_API').strip()
client = OpenAI(api_key=openai_key)
def get_embeddings(text):
  response= client.embeddings.create(model="text-embedding-3-small",input=text)
  return response.data[0].embedding

