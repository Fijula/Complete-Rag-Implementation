import chromadb
chroma_client=chromadb.Client(Settings(persist_directory="./chrom_store"))
collection=chroma_client.get_or_create_collection(name="my-kb")

for i,chunk in enumerate(knwoledge_chunks):
  # print(chunk)
  collection.add(
      ids=[f"chunk-{i+1}"],
      documents=[chunk],
      embeddings=[get_embeddings(chunk)]
  )

query="how many overs in test match"
query_emb=get_embeddings(query)
results=collection.query(
    query_embeddings=[query_emb],
    n_results=2
)
print(results)

context="\n".join(results)

